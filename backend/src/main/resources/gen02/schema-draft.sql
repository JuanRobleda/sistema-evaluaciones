-- Esquema experimental exclusivo de gen02-draft. NO es una migración aprobada.
CREATE TABLE IF NOT EXISTS gen02_sujeto (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 referencia VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS gen02_periodo (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS gen02_test (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(40) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS gen02_version (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 test_id BIGINT NOT NULL REFERENCES gen02_test,
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('BORRADOR','PUBLICADA','RETIRADA'))
);
CREATE TABLE IF NOT EXISTS gen02_configuracion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version_id BIGINT NOT NULL REFERENCES gen02_version,
 codigo VARCHAR(40) NOT NULL,
 orden INTEGER NOT NULL CHECK (orden > 0),
 duracion_segundos INTEGER NOT NULL CHECK (duracion_segundos > 0),
 UNIQUE(version_id,codigo), UNIQUE(version_id,orden)
);
CREATE TABLE IF NOT EXISTS gen02_evaluacion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 test_id BIGINT NOT NULL REFERENCES gen02_test,
 version_id BIGINT NOT NULL REFERENCES gen02_version,
 sujeto_id BIGINT NOT NULL REFERENCES gen02_sujeto,
 periodo_id BIGINT NOT NULL REFERENCES gen02_periodo,
 modalidad VARCHAR(20) NOT NULL CHECK (modalidad='INDIVIDUAL'),
 alcance VARCHAR(20) NOT NULL CHECK (alcance IN ('COMPLETA','PARCIAL')),
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('EN_CURSO','FINALIZADA')),
 fecha_inicio TIMESTAMPTZ NOT NULL,
 fecha_fin TIMESTAMPTZ,
 responsable VARCHAR(120) NOT NULL,
 letra_inicial VARCHAR(1)
);
CREATE UNIQUE INDEX IF NOT EXISTS gen02_unica_abierta ON gen02_evaluacion(sujeto_id,test_id,periodo_id) WHERE estado='EN_CURSO';
CREATE TABLE IF NOT EXISTS gen02_ejecucion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evaluacion_id BIGINT NOT NULL REFERENCES gen02_evaluacion,
 configuracion_id BIGINT NOT NULL REFERENCES gen02_configuracion,
 codigo VARCHAR(40) NOT NULL,
 orden INTEGER NOT NULL CHECK (orden>0),
 duracion_segundos INTEGER NOT NULL CHECK (duracion_segundos>0),
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE','ACTIVA','CERRADA')),
 inicio TIMESTAMPTZ,
 fin_limite TIMESTAMPTZ,
 motivo_cierre VARCHAR(40),
 UNIQUE(evaluacion_id,configuracion_id), UNIQUE(evaluacion_id,orden),
 CHECK ((estado='PENDIENTE' AND inicio IS NULL AND fin_limite IS NULL) OR (estado IN ('ACTIVA','CERRADA') AND inicio IS NOT NULL AND fin_limite>inicio))
);
CREATE UNIQUE INDEX IF NOT EXISTS gen02_unica_activa ON gen02_ejecucion(evaluacion_id) WHERE estado='ACTIVA';
CREATE INDEX IF NOT EXISTS gen02_vencimientos ON gen02_ejecucion(fin_limite) WHERE estado='ACTIVA';
CREATE TABLE IF NOT EXISTS gen02_permiso (
 usuario VARCHAR(120) NOT NULL,
 rol VARCHAR(20) NOT NULL CHECK (rol IN ('SUJETO','ACADEMICO','COORDINADOR','PSICOLOGO','DECANO')),
 sujeto_id BIGINT NOT NULL REFERENCES gen02_sujeto,
 periodo_id BIGINT NOT NULL REFERENCES gen02_periodo,
 permiso VARCHAR(60) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 PRIMARY KEY(usuario,sujeto_id,periodo_id,permiso)
);
CREATE TABLE IF NOT EXISTS gen02_auditoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evaluacion_id BIGINT NOT NULL REFERENCES gen02_evaluacion,
 usuario VARCHAR(120) NOT NULL,
 accion VARCHAR(60) NOT NULL,
 instante TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS gen02_cierre_pendiente (
 ejecucion_id BIGINT PRIMARY KEY REFERENCES gen02_ejecucion,
 instante_oficial TIMESTAMPTZ NOT NULL,
 estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE_CALIFICACION'
);
